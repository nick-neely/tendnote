function fingerprint(input: {
  recordKind: "memory" | "source_record";
  recordId: string;
  text: string;
}) {
  return createHash("sha256")
    .update(input.recordKind)
    .update("\0")
    .update(input.recordId)
    .update("\0")
    .update(input.text)
    .digest("hex");
}

function embeddingFor(input: {
  id: string;
  personId: string | null;
  recordKind: "memory" | "source_record";
  recordId: string;
  embeddedText: string;
  trustLevel: "confirmed_fact" | "logged_context";
  sensitivity?: "normal" | "sensitive" | "restricted";
  sourceUpdatedAt: Date;
}): DemoEmbedding {
  const embedding = fakeVectorForText(input.embeddedText);

  return {
    id: input.id,
    ownerUserId: demoOwnerUserId,
    personId: input.personId,
    recordKind: input.recordKind,
    recordId: input.recordId,
    embedding,
    embeddingModel,
    embeddingVersion,
    embeddingDimensions: embedding.length,
    embeddedText: input.embeddedText,
    contentFingerprint: fingerprint({
      recordKind: input.recordKind,
      recordId: input.recordId,
      text: input.embeddedText,
    }),
    trustLevel: input.trustLevel,
    sensitivity: input.sensitivity ?? "normal",
    sourceUpdatedAt: input.sourceUpdatedAt,
    createdAt: input.sourceUpdatedAt,
    updatedAt: input.sourceUpdatedAt,
  };
}

